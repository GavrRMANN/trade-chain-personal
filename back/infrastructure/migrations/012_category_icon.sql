-- Иконка категории — текстовый смайлик.
--
-- Карточки категорий в каталоге показывают иконку рядом с названием.
-- Иконка приходит с бэкенда как обычный текст (emoji), без отдельного
-- хранилища изображений: фронту не нужно ничего, кроме готовой строки.
--
-- Пустая строка вместо NULL — как full_name у customers, чтобы в запросах
-- не появлялся COALESCE.
--
-- Миграцию безопасно прогнать повторно.

ALTER TABLE categories
    ADD COLUMN IF NOT EXISTS icon VARCHAR(16) NOT NULL DEFAULT '';

-- ---------- иконки демо-категорий ----------

-- Категории из 006 заведены до появления колонки: тот файл генерируется из
-- front/mock-api/data.js и на пустой базе выполняется раньше этой миграции.
-- Сопоставление по name, а не по category_id: имя в mock-данных стабильно,
-- а uuid пересчитывается из строкового ключа при каждой перегенерации.
UPDATE categories AS c
SET icon = seed.icon
FROM (VALUES
    ('Товары для компьютера', '🖥️'),
    ('Комплектующие',         '🔧'),
    ('Видеокарты',            '🎮'),
    ('Игры для приставок',    '🕹️')
) AS seed(name, icon)
WHERE c.name = seed.name
  AND c.icon = '';
